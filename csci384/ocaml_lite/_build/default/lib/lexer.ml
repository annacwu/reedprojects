type token =
  | Type             (** type - keyword *)
  | Of               (** of - keyword *)
  | Let              (** let - keyword *)
  | Rec              (** rec - keyword *)
  | In               (** in - keyword *)
  | If               (** if - keyword *)
  | Then             (** then - keyword *)
  | Else             (** else - keyword *)
  | Match            (** match - keyword *)
  | With             (** with - keyword *)
  | Fun              (** fun - keyword *)
  | True             (** true - keyword *)
  | False            (** false - keyword *)
  | Mod              (** mod - keyword *)
  | TInt             (** int - type name *)
  | TBool            (** bool - type name *)
  | TString          (** string - type name *)
  | TUnit            (** unit - type name *)
  | Eq               (** = - binary operator *)
  | Plus             (** + - binary operator *)
  | Minus            (** - - binary operator *)
  | Times            (** * - binary operator *)
  | Divide           (** / - binary operator *)
  | Lt               (** < - binary operator *)
  | Concat           (** ^ - binary operator *)
  | And              (** && - binary operator *)
  | Or               (** || - binary operator *)
  | Not              (** ! - unary operator *)
  | Negate           (** ~ - unary operator *)
  | DoubleSemicolon  (** ;; *)
  | Colon            (** : *)
  | Arrow            (** -> *)
  | DoubleArrow      (** => *)
  | LParen           (** ( *)
  | RParen           (** ) *)
  | Pipe             (** | *)
  | Comma            (** , *)
  | Id of string     (** Identifier, like a variable or function name *)
  | Tid of string    (** Type identifier *)
  | Int of int       (** Integer literal *)
  | String of string (** String literal *)
  | EOF              (** End-of-file - you can ignore this *)

let tok_to_str : token -> string = function
  | Type -> "type"
  | Of -> "of"
  | Let -> "let"
  | Rec -> "rec"
  | In -> "in"
  | If -> "if"
  | Then -> "then"
  | Else -> "else"
  | Match -> "match"
  | With -> "with"
  | Fun -> "fun"
  | True -> "true"
  | False -> "false"
  | Mod -> "mod"
  | TInt -> "int"
  | TBool -> "bool"
  | TString -> "string"
  | TUnit -> "unit"
  | Eq -> "="
  | Plus -> "+"
  | Minus -> "-"
  | Times -> "*"
  | Divide -> "/"
  | Lt -> "<"
  | Concat -> "^"
  | And -> "&&"
  | Or -> "||"
  | Not -> "not"
  | Negate -> "~"
  | DoubleSemicolon -> ";;"
  | Colon -> ":"
  | Arrow -> "->"
  | DoubleArrow -> "=>"
  | LParen -> "("
  | RParen -> ")"
  | Pipe -> "|"
  | Comma -> ","
  | Id id -> id
  | Tid id -> "'" ^ id
  | Int i -> string_of_int i
  | String s -> "\"" ^ s ^ "\""
  | EOF -> "<eof>"

